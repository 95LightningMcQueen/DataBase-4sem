CREATE OR ALTER PROCEDURE COUNT_SUBJECTS
        @COUNT_FPK INT OUTPUT, 
        @COUNT_FPM INT OUTPUT, 
        @SAME_SUBJECTS INT OUTPUT
AS
BEGIN
    SELECT @COUNT_FPK = COUNT(DISTINCT WORK.SUBJ_ID) FROM WORK
    JOIN HOURS ON WORK.HOURS_ID = HOURS.ID
    JOIN FACULTY ON HOURS.FACULTY_ID = FACULTY.ID
    WHERE FACULTY.FACULTY_NAME = 'ФПК';
    SELECT @COUNT_FPM = COUNT(DISTINCT WORK.SUBJ_ID) FROM WORK
    JOIN HOURS ON WORK.HOURS_ID = HOURS.ID
    JOIN FACULTY ON HOURS.FACULTY_ID = FACULTY.ID
    WHERE FACULTY.FACULTY_NAME = 'ФПМ';
    SELECT @SAME_SUBJECTS = COUNT(DISTINCT WORK.SUBJ_ID) FROM WORK
    JOIN HOURS ON WORK.HOURS_ID = HOURS.ID
    JOIN FACULTY ON HOURS.FACULTY_ID = FACULTY.ID
    WHERE FACULTY.FACULTY_NAME = 'ФПК' AND WORK.SUBJ_ID IN 
    (
        SELECT WORK.SUBJ_ID FROM WORK
        JOIN HOURS ON WORK.HOURS_ID = HOURS.ID
        JOIN FACULTY ON HOURS.FACULTY_ID = FACULTY.ID
        WHERE FACULTY.FACULTY_NAME = 'ФПМ'
    );
    DECLARE @UNIQUE_SUBJECTS INT = @COUNT_FPK + @COUNT_FPM;
    PRINT CONCAT('Для ФПК читается ', @COUNT_FPK, ' предметов,');
    PRINT CONCAT('Для ФПМ читается ', @COUNT_FPM, ' предметов,');
    PRINT CONCAT('Всего предметов ', @UNIQUE_SUBJECTS, ' (из которых ', @SAME_SUBJECTS, ' идентичны).');
END;
GO

DECLARE @FPK INT, @FPM INT, @SAME INT;
EXEC COUNT_SUBJECTS @FPK OUTPUT, @FPM OUTPUT, @SAME OUTPUT;

