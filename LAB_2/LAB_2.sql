USE LAB_2

CREATE TABLE STUD
(
    ID INT IDENTITY(1,1) PRIMARY KEY,
    LAST_NAME NVARCHAR(30),
    F_NAME NVARCHAR(30),
    S_NAME NVARCHAR(30),
    BR_DATE DATE,
    IN_DATE DATE,
    EXM FLOAT
);

CREATE TABLE FACULTY 
(
    ID INT IDENTITY(1,1) PRIMARY KEY,
    FACULTY_NAME NVARCHAR(50)
);

CREATE TABLE FORM
(
    ID INT IDENTITY(1,1) PRIMARY KEY,
    FORM_NAME NVARCHAR(30)
);

CREATE TABLE HOURS 
(
    ID INT IDENTITY(1,1) PRIMARY KEY,
    COURSE INT,
    FACULTY_ID INT,
    FORM_ID INT,
    ALL_H INT,
    INCLASS_H INT,
    FOREIGN KEY (FACULTY_ID) REFERENCES FACULTY(ID),
    FOREIGN KEY (FORM_ID) REFERENCES FORM(ID)
);

CREATE TABLE PROCESS
(
    STUD_ID INT,
    HOURS_ID INT,
    PRIMARY KEY (STUD_ID, HOURS_ID),
    FOREIGN KEY (STUD_ID) REFERENCES STUD(ID),
    FOREIGN KEY (HOURS_ID) REFERENCES HOURS(ID)
);

CREATE TABLE SUBJ
(
    ID INT IDENTITY(1,1) PRIMARY KEY,
    SUBJ NVARCHAR(30),
    HOURS INT
);

CREATE TABLE TEACH
(
    ID INT IDENTITY(1,1) PRIMARY KEY,
    LAST_NAME NVARCHAR(30),
    F_NAME NVARCHAR(30),
    S_NAME NVARCHAR(30),
    BR_DATE DATE,
    START_WORK_DAY DATE
);

CREATE TABLE WORK
(
    TEACH_ID INT,
    SUBJ_ID INT,
    HOURS_ID INT,
    PRIMARY KEY(TEACH_ID, SUBJ_ID, HOURS_ID),
    FOREIGN KEY(HOURS_ID) REFERENCES HOURS(ID),
    FOREIGN KEY(SUBJ_ID) REFERENCES SUBJ(ID),
    FOREIGN KEY(TEACH_ID) REFERENCES TEACH(ID)
);


