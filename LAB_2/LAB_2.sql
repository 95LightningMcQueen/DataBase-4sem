CREATE OR ALTER PROCEDURE ADD_STUDENT_TO_FIRST_COURSE
    @FACULTY_NAME NVARCHAR(50),
    @FORM_NAME NVARCHAR(30),
    @BIRTH_DATE DATE,
    @ADMISSION_DATE DATE,
    @LAST_NAME NVARCHAR(30),
    @F_NAME NVARCHAR(30),
    @S_NAME NVARCHAR(30)
AS
BEGIN
    DECLARE @FACULTY_ID INT;
    DECLARE @FORM_ID INT;
    DECLARE @HOURS_ID INT;
    DECLARE @NEW_STUD_ID INT;
    SELECT @FACULTY_ID = FACULTY.ID FROM FACULTY 
    WHERE FACULTY.FACULTY_NAME = @FACULTY_NAME;
    SELECT @FORM_ID = FORM.ID FROM FORM 
    WHERE FORM.FORM_NAME = @FORM_NAME;
    SELECT @HOURS_ID = HOURS.ID FROM HOURS 
    WHERE HOURS.FACULTY_ID = @FACULTY_ID AND HOURS.FORM_ID = @FORM_ID AND HOURS.COURSE = 1;
    IF @FACULTY_ID IS NULL
    BEGIN
        PRINT 'Ошибка. Факультет "' + @FACULTY_NAME + '" не найден.';
        RETURN;
    END
    IF @FORM_ID IS NULL
    BEGIN
        PRINT 'Ошибка. Форма обучения "' + @FORM_NAME + '" не найдена.';
        RETURN;
    END
    IF @HOURS_ID IS NULL
    BEGIN
        PRINT 'Ошибка. Комбинация факультета и формы обучения для 1 курса не существует.';
        RETURN;
    END
    INSERT INTO STUD (LAST_NAME, F_NAME, S_NAME, BR_DATE, IN_DATE) VALUES 
    (@LAST_NAME, @F_NAME, @S_NAME, @BIRTH_DATE, @ADMISSION_DATE);
    SELECT @NEW_STUD_ID = MAX(STUD.ID) FROM STUD;
    INSERT INTO PROCESS (STUD_ID, HOURS_ID) VALUES (@NEW_STUD_ID, @HOURS_ID);
    PRINT 'Студент ' + @LAST_NAME + ' успешно зачислен на 1 курс.';
END;
GO

